def clean_base64(base64_string: str) -> str:
    """Clean base64 string by removing data URL prefix."""
    return base64_string.replace("data:.*?;base64,", "", 1)


async def convert_pdf_to_text(base64_pdf: str) -> str:
    """Convert PDF from base64 to text."""
    try:
        cleaned_base64 = clean_base64(base64_pdf)
        pdf_bytes = base64.b64decode(cleaned_base64)

        # Convert PDF to images
        images = pdf2image.convert_from_bytes(pdf_bytes)

        # Extract text from images
        text = ""
        for image in images:
            # TODO: Implement OCR here if needed
            # For now, just convert image to string representation
            text += str(image)

        return text
    except Exception as e:
        print(f"Error converting PDF to text: {e}")
        raise


async def create_context_document_messages_anthropic(
    documents: List[ContextDocument],
    *,
    native_support: bool = False,
) -> List[Dict[str, Any]]:
    """Create context document messages for Anthropic models."""
    messages = []
    for doc in documents:
        if doc["type"] == "application/pdf" and native_support:
            messages.append({
                "type": "document",
                "source": {
                    "type": "base64",
                    "media_type": doc["type"],
                    "data": clean_base64(doc["data"]),
                },
            })
            continue

        text = ""
        if doc["type"] == "application/pdf" and not native_support:
            text = await convert_pdf_to_text(doc["data"])
        elif doc["type"].startswith("text/"):
            text = base64.b64decode(clean_base64(doc["data"])).decode()
        elif doc["type"] == "text":
            text = doc["data"]

        messages.append({
            "type": "text",
            "text": text,
        })

    return messages


def create_context_document_messages_gemini(
    documents: List[ContextDocument]
) -> List[Dict[str, Any]]:
    """Create context document messages for Gemini models."""
    messages = []
    for doc in documents:
        if doc["type"] == "application/pdf":
            messages.append({
                "type": doc["type"],
                "data": clean_base64(doc["data"]),
            })
        elif doc["type"].startswith("text/"):
            messages.append({
                "type": "text",
                "text": base64.b64decode(clean_base64(doc["data"])).decode(),
            })
        elif doc["type"] == "text":
            messages.append({
                "type": "text",
                "text": doc["data"],
            })
        else:
            raise ValueError(f"Unsupported document type: {doc['type']}")
    return messages


async def create_context_document_messages_openai(
    documents: List[ContextDocument]
) -> List[Dict[str, Any]]:
    """Create context document messages for OpenAI models."""
