async def get_user_from_config(config: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """Get user from config using Supabase."""
    supabase_url = os.getenv("NEXT_PUBLIC_SUPABASE_URL")
    supabase_key = os.getenv("SUPABASE_SERVICE_ROLE")
    if not supabase_url or not supabase_key:
        return None

    access_token = config.get("configurable", {}).get(
        "supabase_session", {}).get("access_token")
    if not access_token:
        return None

    supabase: Client = create_client(supabase_url, supabase_key)
    auth_res = await supabase.auth.get_user(access_token)
    return auth_res.user if auth_res else None


