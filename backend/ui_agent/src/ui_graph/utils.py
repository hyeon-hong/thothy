def format_reflections(
    reflections: Reflections,
    *,
    only_style: bool = False,
    only_content: bool = False,
) -> str:
    """Format reflections into a string."""
    if only_style and only_content:
        raise ValueError(
            "Cannot specify both `only_style` and `only_content` as true.")

    style_rules_arr = reflections.get("style_rules", [])
    style_rules_str = "No style guidelines found."
    if not isinstance(style_rules_arr, list):
        try:
            style_rules_arr = json.loads(style_rules_arr)
            style_rules_str = "\n- ".join(style_rules_arr)
        except Exception as e:
            print(
                f"FAILED TO PARSE STYLE RULES.\n\ntype: {type(style_rules_arr)}\n\n"
                f"style_rules: {style_rules_arr}\n\nerror: {e}"
            )

    content_rules_arr = reflections.get("content", [])
    content_rules_str = "No memories/facts found."
    if not isinstance(content_rules_arr, list):
        try:
            content_rules_arr = json.loads(content_rules_arr)
            content_rules_str = "\n- ".join(content_rules_arr)
        except Exception as e:
            print(
                f"FAILED TO PARSE CONTENT RULES.\n\ntype: {type(content_rules_arr)}\n\n"
                f"content_rules: {content_rules_arr}\n\nerror: {e}"
            )

    style_string = f"""The following is a list of style guidelines previously generated by you:
<style-guidelines>
- {style_rules_str}
</style-guidelines>"""

    content_string = f"""The following is a list of memories/facts you previously generated about the user:
<user-facts>
- {content_rules_str}
</user-facts>"""

    if only_style:
        return style_string
    if only_content:
        return content_string

    return f"{style_string}\n\n{content_string}"


def ensure_store_in_config(config: Dict[str, Any]) -> Any:
    """Ensure store exists in config."""
    if "store" not in config:
        raise ValueError("`store` not found in config")
    return config["store"]


async def get_formatted_reflections(config: Dict[str, Any]) -> str:
    """Get formatted reflections from store."""
    if "store" not in config:
        return "No reflections found."

    store = ensure_store_in_config(config)
    assistant_id = config.get("configurable", {}).get("assistant_id")
    if not assistant_id:
        raise ValueError("`assistant_id` not found in configurable")

    memory_namespace = ["memories", assistant_id]
    memory_key = "reflection"
    memories = await store.get(memory_namespace, memory_key)
    memories_as_string = (
        format_reflections(memories.value)
        if memories and hasattr(memories, "value")
        else "No reflections found."
    )

    return memories_as_string


def format_artifact_content(
    content: Union[ArtifactMarkdownV3, ArtifactCodeV3],
    shorten_content: bool = False,
) -> str:
    """Format artifact content into a string."""
    if is_artifact_code_content(content):
        artifact_content = (
            content["code"][:500] if shorten_content else content["code"]
        )
    else:
        artifact_content = (
            content["full_markdown"][:500]
            if shorten_content
            else content["full_markdown"]
        )
    return f"Title: {content['title']}\nArtifact type: {content['type']}\nContent: {artifact_content}"


def format_artifact_content_with_template(
    template: str,
    content: Union[ArtifactMarkdownV3, ArtifactCodeV3],
    shorten_content: bool = False,
) -> str:
    """Format artifact content using a template."""
    return template.replace(
        "{artifact}",
        format_artifact_content(content, shorten_content)
    )


def get_model_config(
    config: Dict[str, Any],
    *,
    is_tool_calling: bool = False,
) -> Dict[str, Any]:
    """Get model configuration from config."""
    custom_model_name = config.get("configurable", {}).get("customModelName")
    if not custom_model_name:
        raise ValueError("Model name is missing in config.")

    model_config = config.get("configurable", {}).get("modelConfig")

    if custom_model_name.startswith("azure/"):
        actual_model_name = custom_model_name.replace("azure/", "")
        if is_tool_calling and "o1" in actual_model_name:
            # Fallback to 4o model for tool calling since o1 does not support tools
            actual_model_name = "gpt-4o"
        return {
            "model_name": actual_model_name,
            "model_provider": "azure_openai",
            "azure_config": {
                "azure_openai_api_key": os.getenv("_AZURE_OPENAI_API_KEY", ""),
                "azure_openai_api_instance_name": os.getenv("_AZURE_OPENAI_API_INSTANCE_NAME", ""),
                "azure_openai_api_deployment_name": os.getenv("_AZURE_OPENAI_API_DEPLOYMENT_NAME", ""),
                "azure_openai_api_version": os.getenv("_AZURE_OPENAI_API_VERSION", "2024-08-01-preview"),
                "azure_openai_base_path": os.getenv("_AZURE_OPENAI_API_BASE_PATH"),
            },
        }

    provider_config = {
        "model_name": custom_model_name,
        "model_config": model_config,
    }

    if any(
        name in custom_model_name
        for name in ["gpt-", "o1", "o3", "Qwen/"]
    ):
        actual_model_name = provider_config["model_name"]
        if is_tool_calling and "o1" in actual_model_name:
            actual_model_name = "gpt-4o"
        return {
            **provider_config,
            "model_name": actual_model_name,
            "model_provider": "openai",
            "api_key": os.getenv("OPENAI_API_KEY"),
        }

    if "claude-" in custom_model_name:
        return {
            **provider_config,
            "model_provider": "anthropic",
            "api_key": os.getenv("ANTHROPIC_API_KEY"),
        }

    if "fireworks/" in custom_model_name:
        actual_model_name = provider_config["model_name"]
        if (
            is_tool_calling
            and actual_model_name != "accounts/fireworks/models/llama-v3p3-70b-instruct"
        ):
            actual_model_name = "accounts/fireworks/models/llama-v3p3-70b-instruct"
        return {
            **provider_config,
            "model_name": actual_model_name,
            "model_provider": "fireworks",
            "api_key": os.getenv("FIREWORKS_API_KEY"),
        }

    if custom_model_name.startswith("groq/"):
        actual_model_name = custom_model_name.replace("groq/", "")
        return {
            "model_name": actual_model_name,
            "model_provider": "groq",
            "api_key": os.getenv("GROQ_API_KEY"),
        }

    if "gemini-" in custom_model_name:
        actual_model_name = provider_config["model_name"]
        if is_tool_calling and "thinking" in actual_model_name:
            actual_model_name = "gemini-2.0-flash-exp"
        return {
            **provider_config,
            "model_name": actual_model_name,
            "model_provider": "google-genai",
            "api_key": os.getenv("GOOGLE_API_KEY"),
        }

    if custom_model_name.startswith("ollama-"):
        return {
            "model_name": custom_model_name.replace("ollama-", ""),
            "model_provider": "ollama",
            "base_url": os.getenv("OLLAMA_API_URL", "http://host.docker.internal:11434"),
        }

    raise ValueError("Unknown model provider")


